// Generates `src/tutor/spec.generated.ts` from the tutor spec in `training/spec`
// (the single source of truth for the on-device tutor's prompt and output
// contract): the system prompt template, error tags, grammar points, level
// bands, the output JSON Schema and the scenario library.
//
//   node packages/core/scripts/generate-tutor-spec.mjs          # write
//   node packages/core/scripts/generate-tutor-spec.mjs --check  # fail if stale
//
// `src/tutor/spec.sync.test.ts` runs the same check, so the TypeScript port
// cannot drift from the training spec.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import * as prettier from 'prettier';

const here = path.dirname(fileURLToPath(import.meta.url));
export const CORE_DIR = path.resolve(here, '..');
export const SPEC_DIR = path.resolve(CORE_DIR, '../../training/spec');
export const OUTPUT = path.join(CORE_DIR, 'src/tutor/spec.generated.ts');

const read = (name) => readFileSync(path.join(SPEC_DIR, name), 'utf8');
const readJson = (name) => JSON.parse(read(name));

/** One Python string constant from `models.py`, e.g. `SPEC_VERSION: Final = "1.0.0"`. */
function pyConstant(source, name) {
  const match = new RegExp(`^${name}(?::[^=]*)? = "([^"]*)"$`, 'm').exec(source);
  if (!match) throw new Error(`${name} not found in training/spec/models.py`);
  return match[1];
}

/** The level bands from `levels.py` (`Level.A1: LevelBand(Level.A1, 500, 8, 2, 1, 0.05, english_allowed=True)`). */
function pyBands(source) {
  const re =
    /Level\.(A1|A2|B1|B2|C1|C2): LevelBand\(Level\.\1, (\d+), (\d+), (\d+), (\d+), ([\d.]+), english_allowed=(True|False)\)/g;
  const bands = {};
  for (const m of source.matchAll(re)) {
    bands[m[1]] = {
      level: m[1],
      lemmaCeiling: Number(m[2]),
      maxWordsPerSentence: Number(m[3]),
      maxSentences: Number(m[4]),
      maxNewWords: Number(m[5]),
      maxOutOfBandRatio: Number(m[6]),
      englishAllowed: m[7] === 'True',
    };
  }
  if (Object.keys(bands).length !== 6) throw new Error('expected 6 level bands in levels.py');
  return bands;
}

const json = (value) => JSON.stringify(value, null, 2);

/** The generated module's source, formatted. */
export async function renderGenerated() {
  const models = read('models.py');
  const specVersion = pyConstant(models, 'SPEC_VERSION');
  const major = specVersion.split('.')[0];
  const tags = readJson('error_tags.json');
  const points = readJson('grammar_points.json');
  const scenarios = readJson(`generated/scenarios.v${major}.json`);
  if (scenarios.specVersion !== specVersion) throw new Error('scenarios.json is stale');
  const source = `// Generated by packages/core/scripts/generate-tutor-spec.mjs from training/spec.
// Do not edit: change the spec, run \`python -m spec export-schema\` in training/
// and then \`node packages/core/scripts/generate-tutor-spec.mjs\`.
import type {
  ErrorTagInfo,
  GrammarPointInfo,
  LevelBand,
  TutorLevel,
  TutorScenario,
} from './types';

/** Version of the tutor spec this module was generated from. */
export const SPEC_VERSION = ${json(specVersion)};

/** The first user message of every conversation: tells the tutor to open the scenario. */
export const START_MESSAGE = ${json(pyConstant(models, 'START_MESSAGE'))};

/** \`training/spec/system_prompt.v${major}.txt\`, a Python \`string.Template\`. */
export const SYSTEM_PROMPT_TEMPLATE = ${json(read(`system_prompt.v${major}.txt`))};

/** Version of the error-tag taxonomy. */
export const TAXONOMY_VERSION = ${json(tags.version)};

/** Learner error tags, in taxonomy order (\`training/spec/error_tags.json\`). */
export const ERROR_TAGS: readonly ErrorTagInfo[] = ${json(tags.tags)};

/** Grammar points in teaching order (\`training/spec/grammar_points.json\`); \`id\` is the content id. */
export const GRAMMAR_POINTS: readonly GrammarPointInfo[] = ${json(points.points)};

/** Limits for tutor replies at each level (\`training/spec/levels.py\`). */
export const LEVEL_BANDS: Readonly<Record<TutorLevel, LevelBand>> = ${json(pyBands(read('levels.py')))};

/** JSON Schema of one tutor turn (\`training/spec/schema/tutor_output.v${major}.schema.json\`). */
export const TUTOR_OUTPUT_SCHEMA: Readonly<Record<string, unknown>> = ${json(
    readJson(`schema/tutor_output.v${major}.schema.json`),
  )};

/** The scenario library (\`training/scenarios/*.yaml\`, validated by the spec). */
export const SCENARIOS: readonly TutorScenario[] = ${json(scenarios.scenarios)};
`;
  const config = await prettier.resolveConfig(OUTPUT);
  return prettier.format(source, { ...config, filepath: OUTPUT });
}

/** Whether the committed module matches the spec. */
export async function isCurrent() {
  return readFileSync(OUTPUT, 'utf8') === (await renderGenerated());
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    if (!(await isCurrent())) {
      console.error(`${OUTPUT} is stale: run node packages/core/scripts/generate-tutor-spec.mjs`);
      process.exit(1);
    }
  } else {
    writeFileSync(OUTPUT, await renderGenerated());
    console.log(`wrote ${OUTPUT}`);
  }
}
