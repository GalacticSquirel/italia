/** Strip the annotation marks, giving the plain lower-case spelling used as the lookup key. */
export function stripAnnotation(accented: string): string {
  return accented.normalize('NFD').replace(/[̀́̂̈]/gu, '').normalize('NFC').toLowerCase();
}

function buildLexicon(): ReadonlyMap<string, LexiconEntry> {
  const map = new Map<string, LexiconEntry>();
  const add = (entry: LexiconEntry): void => {
    const key = stripAnnotation(entry.accented);
    const existing = map.get(key);
    // A later special entry can add z/gl/homograph data to an earlier stress entry.
    map.set(key, existing ? { ...existing, ...entry } : entry);
  };
  for (const list of [PROPAROXYTONES, HIATUS, OXYTONES, MID_VOWEL_QUALITY]) {
    for (const accented of list) add({ accented });
  }
  for (const entry of SPECIAL) add(entry);
  return map;
}

/** The lexicon, keyed by plain lower-case spelling. */
export const LEXICON: ReadonlyMap<string, LexiconEntry> = buildLexicon();

/** Number of entries in each list, exposed for tests and documentation. */
export const LEXICON_LIST_SIZES = {
  proparoxytones: PROPAROXYTONES.length,
  hiatus: HIATUS.length,
  oxytones: OXYTONES.length,
  midVowelQuality: MID_VOWEL_QUALITY.length,
  special: SPECIAL.length,
} as const;

/** Look a plain lower-case spelling up in {@link LEXICON}. */
export function lookupLexicon(plain: string): LexiconEntry | undefined {
  return LEXICON.get(plain);
}
