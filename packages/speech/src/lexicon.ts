/**
 * Pronunciation lexicon for words whose stress, mid-vowel quality or `z`
 * voicing the spelling does not show.
 *
 * Entries are written in an annotated spelling: the word's own letters with a
 * mark on the stressed vowel.
 *
 * - `à ì ù`: stress on that vowel.
 * - `é ó`: stress on a close-mid vowel (/e/, /o/); `è ò`: stress on an open-mid
 *   vowel (/ɛ/, /ɔ/).
 * - `ê ô`: stress on a mid vowel whose quality this lexicon does not assert
 *   (the G2P then applies its rules or reports the quality as unknown).
 *
 * Only quality marks we are confident of for standard (neutral, Tuscan-based)
 * Italian are used; anything doubtful is written with `ê`/`ô`.
 *
 * @packageDocumentation
 */

/** Affricate value for one `z` or `zz` group. */
export type ZValue = 'ts' | 'dz';

/** What the lexicon knows about one word. */
export interface LexiconEntry {
  /** The word in annotated spelling (see the module docs). */
  readonly accented: string;
  /** Voicing of each `z`/`zz` group, in order of appearance. */
  readonly z?: readonly ZValue[];
  /** `gl` before `i` is /ɡl/, not /ʎ/ (*glicine*). */
  readonly hardGl?: boolean;
  /** Other readings of the same spelling (annotated), when the spelling is ambiguous. */
  readonly homographs?: readonly string[];
}

