describe('g2p golden transcriptions', () => {
  for (const [rule, words] of Object.entries(GOLDEN)) {
    describe(rule, () => {
      for (const [word, ipa] of Object.entries(words)) {
        it(`${word} → ${ipa}`, () => {
          const result = g2p(word);
          expect(result.words).toHaveLength(1);
          expect(result.words[0]?.ipa).toBe(ipa);
        });
      }
    });
  }

  it('covers at least 150 words', () => {
    const count = Object.values(GOLDEN).reduce((n, words) => n + Object.keys(words).length, 0);
    expect(count).toBeGreaterThanOrEqual(150);
  });
});
